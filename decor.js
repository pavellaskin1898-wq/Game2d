/* =========================================================
   decor.js — пиксельное наполнение ангара (SVG, crispEdges)
   Всё рисуется «квадратиками» по сетке 4px: стены, фермы,
   ворота, кран-балка, стеллажи с запчастями, ящики, бочки,
   тележка, конусы, масло, кабели, робот-погрузчик.
   ========================================================= */
(function () {
  const P = 4; // размер «пикселя»
  const px = (x, y, w, h, c) =>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${c}"/>`;

  // ---- фоновая стена, пол, конструкции ----
  function backLayer() {
    let s = "";
    // стена ангара
    s += px(-10, -10, 420, 380, "#232c3d");
    // панели стены (вертикальные швы)
    for (let x = -6; x < 410; x += 52) s += px(x, -10, P, 380, "#1b2331");
    // горизонтальный пояс стены
    s += px(-10, 120, 420, P * 2, "#1b2331");
    s += px(-10, 128, 420, P, "#2e3a52");
    // верхние окна-иллюминаторы (жёлтый свет)
    for (let i = 0; i < 5; i++) {
      const x = 18 + i * 84;
      s += px(x, 14, 40, 20, "#10161f");
      s += px(x + P, 14 + P, 32, 12, i % 2 ? "#ffd23f" : "#ffdd6e");
      s += px(x + P, 14 + P, 32, P, "#fff3b0"); // блик
    }
    // ферма под потолком (диагональные решётки квадратиками)
    s += px(-10, 44, 420, P * 2, "#39465c");
    s += px(-10, 72, 420, P * 2, "#39465c");
    for (let x = -8; x < 408; x += 24) {
      s += px(x, 52, P * 2, P * 2, "#39465c");
      s += px(x + 12, 60, P * 2, P * 2, "#39465c");
      s += px(x + 8, 52, P * 2, P * 2, "#39465c");
      s += px(x + 16, 60, P * 2, P * 2, "#39465c");
    }
    // опорные балки
    s += px(2, -10, P * 4, 380, "#2e3a52");
    s += px(392, -10, P * 4, 380, "#2e3a52");
    // кран-балка с цепью и крюком
    s += px(60, 88, 300, P * 3, "#f2a33c");
    s += px(60, 88, P, P * 3, "#c77f22");
    s += px(176, 96, P * 5, P * 3, "#39465c"); // тележка крана
    for (let y = 108; y < 150; y += 6) s += px(186, y, P * 2, P * 2, "#8b97ab"); // цепь
    s += px(184, 150, P * 3, P * 2, "#c9ced9"); // скоба крюка
    s += px(186, 158, P * 2, P * 2, "#c9ced9");
    s += px(188, 162, P * 2, P * 2, "#c9ced9");
    s += px(190, 158, P * 2, P, "#c9ced9");

    // ---- большие ворота ангара слева ----
    s += px(-10, 150, 108, 220, "#1a2130");
    s += px(-10, 150, 108, P * 2, "#39465c");
    for (let x = -6; x < 96; x += 20) s += px(x, 158, P, 212, "#232c3d"); // секции
    s += px(-10, 340, 108, P * 3, "#f2a33c");
    s += px(-10, 340, 108, P, "#ffdd6e");
    // предупредительные полосы на раме ворот
    for (let y = 158; y < 360; y += 16) {
      s += px(90, y, P * 3, 8, "#f2a33c");
      s += px(90, y + 8, P * 3, 8, "#10161f");
    }

    // ---- прожекторы на стене ----
    for (const x of [120, 268, 356]) {
      s += px(x, 96, P * 4, P * 2, "#39465c");
      s += px(x + P, 104, P * 3, P * 2, "#ffe9a8");
      // конус света (полупрозрачный, из квадратиков)
      for (let r = 0; r < 4; r++)
        s += `<rect x="${x - 4 + r * -2}" y="${112 + r * 10}" width="${24 + r * 8}" height="10" fill="#ffe9a8" opacity="0.05"/>`;
    }

    // ---- задний стеллаж с запчастями (справа) ----
    const sx = 300, sy = 190;
    s += px(sx, sy, 96, P * 2, "#4a5a75");            // верхняя полка
    s += px(sx, sy + 44, 96, P * 2, "#4a5a75");       // средняя
    s += px(sx, sy + 88, 96, P * 2, "#4a5a75");       // нижняя
    s += px(sx, sy, P * 2, 180, "#39465c");           // стойки
    s += px(sx + 88, sy, P * 2, 180, "#39465c");
    s += px(sx + 44, sy, P * 2, 180, "#39465c");
    // запчасти: шестерни (квадратичные), цилиндры, головы-заготовки
    s += px(sx + 8, sy - 20, 16, 20, "#8b97ab");
    s += px(sx + 10, sy - 24, 12, 4, "#c9ced9");
    s += px(sx + 30, sy - 16, 12, 16, "#4dd2ff");     // банка смазки
    s += px(sx + 30, sy - 20, 12, 4, "#2b8fb5");
    s += px(sx + 52, sy - 26, 20, 26, "#5c6b84");     // ящик ЗИП
    s += px(sx + 54, sy - 20, 16, P, "#f2a33c");
    s += px(sx + 76, sy - 18, 12, 18, "#ff7b7b");     //red part
    s += px(sx + 8, sy + 24, 18, 20, "#c0392b");      // бочонок
    s += px(sx + 8, sy + 28, 18, P, "#7a2018");
    s += px(sx + 30, sy + 22, 12, 22, "#8b97ab");
    s += px(sx + 46, sy + 26, 26, 18, "#39465c");     // гусеница/резина
    s += px(sx + 48, sy + 30, 4, 4, "#8b97ab");
    s += px(sx + 56, sy + 30, 4, 4, "#8b97ab");
    s += px(sx + 64, sy + 30, 4, 4, "#8b97ab");
    s += px(sx + 78, sy + 20, 14, 24, "#ffd23f");     // канистра
    s += px(sx + 82, sy + 16, 6, 4, "#c9a227");
    s += px(sx + 10, sy + 68, 20, 20, "#4dd2ff");     // корпусная деталь
    s += px(sx + 14, sy + 72, 12, 4, "#bff0ff");
    s += px(sx + 36, sy + 64, 16, 24, "#5c6b84");
    s += px(sx + 58, sy + 70, 24, 18, "#2e3a52");
    s += px(sx + 60, sy + 74, 20, P, "#8b97ab");
    s += px(sx + 86, sy + 66, 8, 22, "#ff5c5c");

    // ---- плакат на стене ----
    s += px(214, 150, 64, 44, "#f4ecd8");
    s += px(214, 150, 64, P, "#3a3226");
    s += px(216, 156, 20, 20, "#c0392b");             // звезда упрощённая
    s += px(222, 152, 8, 28, "#c0392b");
    s += px(212, 162, 28, 8, "#c0392b");
    s += px(242, 158, 32, P * 2, "#3a3226");          // текст-полоски
    s += px(242, 168, 26, P * 2, "#3a3226");
    s += px(242, 178, 30, P * 2, "#3a3226");

    // ---- пол: плитка + разметка сектора сборки ----
    s += px(-10, 360, 420, 170, "#2b3648");
    for (let x = -10; x < 410; x += 32) s += px(x, 360, P / 2, 170, "#242e3e");
    for (let y = 368; y < 530; y += 28) s += px(-10, y, 420, P / 2, "#242e3e");
    // жёлтая разметка
    for (let x = -10; x < 410; x += 24) {
      s += px(x, 362, 14, P * 2, "#f2a33c");
      s += px(x, 362, 14, P, "#ffdd6e");
    }
    s += px(120, 470, P * 2, 60, "#f2a33c");
    s += px(268, 470, P * 2, 60, "#f2a33c");
    for (let y = 470; y < 530; y += 16) {
      s += px(128, y, 132, P * 2, "#f2a33c");
    }
    return s;
  }

  // ---- объекты перед мехом ----
  function frontLayer() {
    let s = "";
    // тень под мехом уже в CSS; добавим масляное пятно
    s += px(150, 500, 40, P * 2, "#141b26");
    s += px(160, 508, 24, P, "#141b26");

    // ---- стопка ящиков слева ----
    const crate = (x, y, w, h, c, d) => {
      let o = px(x, y, w, h, c) + px(x, y, w, P, d) + px(x, y + h - P, w, P, d) +
              px(x, y, P, h, d) + px(x + w - P, y, P, h, d) +
              px(x + 4, y + h / 2 - P, w - 8, P * 2, d);
      return o;
    };
    s += crate(24, 452, 56, 44, "#7a4c22", "#4a2d12");
    s += crate(32, 412, 44, 40, "#8a5a34", "#5a3a1c");
    s += px(36, 420, 12, 12, "#4dd2ff"); // маркировка «хрупкое»
    s += px(56, 424, 16, P, "#ffd23f");
    // гаечный ключ прислонён
    s += px(84, 468, P * 2, 40, "#8b97ab");
    s += px(80, 462, 12, 10, "#8b97ab");
    s += px(84, 466, 4, 4, "#232c3d");

    // ---- бочки справа ----
    const barrel = (x, y, c, d) =>
      px(x, y, 28, 44, c) + px(x, y, 28, P, d) + px(x, y + 12, 28, P * 2, d) +
      px(x, y + 30, 28, P * 2, d) + px(x + 4, y + 4, 4, 4, "#ffffff") ;
    s += barrel(330, 448, "#c0392b", "#7a2018");
    s += barrel(356, 456, "#2e8b57", "#1d5c39");
    // канистра масла
    s += px(318, 486, 16, 22, "#ffd23f");
    s += px(322, 482, 8, 4, "#c9a227");
    s += px(320, 492, 12, P, "#7a5b12");

    // ---- конус безопасности ----
    s += px(292, 508, 32, P * 2, "#10161f");
    s += px(300, 492, 16, 16, "#ff7b3d");
    s += px(304, 480, 8, 12, "#ff7b3d");
    s += px(306, 472, 4, 8, "#ff7b3d");
    s += px(302, 496, 12, P * 2, "#ffffff");
    s += px(305, 484, 6, P * 2, "#ffffff");

    // ---- тележка с запчастями (перед ногами, не загораживает) ----
    s += px(12, 500, 84, P * 3, "#39465c");           // столешница
    s += px(12, 500, 84, P, "#8b97ab");
    s += px(16, 512, P * 2, 16, "#2e3a52");
    s += px(88, 512, P * 2, 16, "#2e3a52");
    s += px(12, 528, 8, 8, "#10161f");                // колёса
    s += px(84, 528, 8, 8, "#10161f");
    // детали на тележке: рука-заготовка, визор, патроны
    s += px(20, 486, 26, 14, "#ffc06a");
    s += px(24, 482, 18, 4, "#d9822b");
    s += px(52, 488, 14, 12, "#ffd23f");
    s += px(54, 490, 10, 4, "#141b26");
    s += px(72, 490, 4, 10, "#c0392b");
    s += px(78, 490, 4, 10, "#c0392b");
    s += px(84, 490, 4, 10, "#c0392b");

    // ---- шланг/кабель на полу ----
    for (let x = 110; x < 150; x += 8) s += px(x, 520, 6, P, "#f2a33c");
    s += px(104, 516, 8, 12, "#39465c");

    // ---- робот-погрузчик (маленький дрон-техник слева у ворот) ----
    s += px(40, 380, 36, 20, "#4dd2ff");
    s += px(40, 380, 36, P, "#2b8fb5");
    s += px(46, 372, 12, 8, "#10161f");               // «глаз»
    s += px(48, 374, 4, 4, "#ffd23f");
    s += px(44, 400, 8, 8, "#10161f");                // колёса
    s += px(64, 400, 8, 8, "#10161f");
    s += px(76, 386, 12, P * 2, "#8b97ab");           // манипулятор
    s += px(86, 382, P * 2, 12, "#8b97ab");

    // ---- лампы под потолком переднего плана ----
    for (const x of [70, 200, 330]) {
      s += px(x + 12, -10, P, 14, "#8b97ab");
      s += px(x, 4, 28, P * 2, "#39465c");
      s += px(x + 4, 12, 20, P, "#fff3b0");
    }
    return s;
  }

  window.HANGAR_DECOR = {
    render() {
      const b = document.getElementById("decorBack");
      const f = document.getElementById("decorFront");
      if (b) b.innerHTML = backLayer();
      if (f) f.innerHTML = frontLayer();
    },
  };
})();
